#!/bin/sh
# Builds bin/d3d11.dll (Windows x64) with the MinGW cross-compiler, and puts the
# default SoraVR.ini and the README next to it, so bin/ is the package to copy
# (plus openxr_loader.dll, see README.md).
set -e
cd "$(dirname "$0")"
mkdir -p bin build
# dist/SoraVR.ini is the single source of the default settings: embedded into the DLL,
# which writes it on first start if the game folder has no SoraVR.ini yet.
python3 - <<'PY'
src = open('dist/SoraVR.ini', encoding='utf-8').read().replace('\r\n', '\n')
out = ['// generated by build.sh from dist/SoraVR.ini - do not edit', 'static const char kDefaultIni[] =']
for line in src.split('\n'):
    esc = line.replace('\\', '\\\\').replace('"', '\\"')
    out.append('    "' + esc + '\\r\\n"')
out[-1] += ';'
open('build/default_ini.h', 'w').write('\n'.join(out) + '\n')
PY
x86_64-w64-mingw32-g++ -std=c++17 -O2 -Wall -shared -static -s -Ibuild \
    -o bin/d3d11.dll src/soravr.cpp src/xr.cpp d3d11.def \
    -luuid -lole32
cp dist/SoraVR.ini bin/SoraVR.default.ini
cp README.md bin/README.md
cp third_party/openxr/LICENSE bin/LICENSE-OpenXR.txt
echo "built bin/d3d11.dll"
